"""Version announcement of the GOSOF80 (test switch with option DIP 3 OFF):
"This is Gosof version <board> dot <minor/10> <minor%10> from lisy dot dev".

Single source of the phoneme sequences. Writes
  rtl/common/votrax/vtx_announce_pkg.vhd   word tables for vtx_announce.vhd
  sim/votrax/stimuli/t6_version.txt        the sentence for board 3, minor 98, to render
                                           it with ref_votrax (PinMAME) and listen to it

Phonemes by SC-01 name. Change the words here, rerun, never edit the .vhd by hand.
Run: python gen_announce.py [board] [minor]   (defaults 3 98, only for t6_version.txt)
"""
import os
import sys

NAMES = ("EH3 EH2 EH1 PA0 DT A1 A2 ZH AH2 I3 I2 I1 M N B V "
         "CH SH Z AW1 NG AH1 OO1 OO L K J H G F D S "
         "A AY Y1 UH3 AH P O I U Y T R E W AE AE1 "
         "AW2 UH2 UH1 UH O2 O1 IU U1 THV TH ER EH E1 AW PA1 STOP").split()
CODE = {n: i for i, n in enumerate(NAMES)}
assert len(NAMES) == 64

# "This is Gosof version"
PRE = "THV I S PA0 I Z PA0 G O U1 S AW1 F PA0 V ER ZH UH1 N PA1"
DIGITS = [
    "Z I3 R O U1",        # zero
    "W UH UH1 N",         # one
    "T U1 U1",            # two
    "TH R E1 Y",          # three
    "F O1 O R",           # four
    "F AH1 EH3 Y V",      # five
    "S I I3 K S",         # six
    "S EH1 EH3 V I3 N",   # seven
    "A1 AY Y T",          # eight
    "N AH1 EH3 Y N",      # nine
]
DOT = "PA0 D AH1 AH2 T PA0"
GAP = "PA0"                # between the two digits of the minor version
# "from lisy dot dev"
POST = "PA1 F R AH1 M PA0 L I1 I3 S I3 Y PA0 D AH1 AH2 T PA0 D EH1 EH3 V PA1 STOP"


def codes(words):
    return [CODE[n] for n in words.split()]


def sentence(board, minor):
    return (codes(PRE) + codes(DIGITS[board % 10]) + codes(DOT) + codes(DIGITS[minor // 10 % 10])
            + codes(GAP) + codes(DIGITS[minor % 10]) + codes(POST))


def bus(code, infl=0):
    """What the MA-216 CPU stores to $2000: P0..P5 inverted, inflection on D6/D7."""
    return (code ^ 0x3F) | (infl << 6)


def vhdl_list(name, cs):
    body = ", ".join(str(c) for c in cs)
    if len(cs) == 1:
        body = "0 => " + body
    return "  constant %s : phon_list_t(0 to %d) := (%s);" % (name, len(cs) - 1, body)


HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))

digit_len = max(len(codes(d)) for d in DIGITS)
lines = [
    "-- GENERATED by sim/votrax/tools/gen_announce.py - do not edit, rerun the script.",
    "--",
    "-- Phoneme tables (SC-01 codes, not inverted) of the version announcement:",
    '-- "This is Gosof version <board> dot <minor/10> <minor%10> from lisy dot dev".',
    "-- vtx_announce.vhd concatenates them from its generics BOARD_ID / SW_MINOR.",
    "",
    "library ieee;",
    "use ieee.std_logic_1164.all;",
    "",
    "package vtx_announce_pkg is",
    "  subtype phon_t is natural range 0 to 63;",
    "  type phon_list_t is array (natural range <>) of phon_t;",
    "  constant PHON_STOP : phon_t := 63;",
    "  constant PHON_PA0  : phon_t := 3;",
    "",
    vhdl_list("ANN_PRE", codes(PRE)),
    vhdl_list("ANN_DOT", codes(DOT)),
    vhdl_list("ANN_GAP", codes(GAP)),
    vhdl_list("ANN_POST", codes(POST)),
    "",
    "  -- digit words, padded with PA0 to %d phonemes; ANN_DIGIT_LEN gives the real length" % digit_len,
    "  constant DIGIT_MAX : natural := %d;" % digit_len,
    "  type digit_tab_t is array (0 to 9) of phon_list_t(0 to DIGIT_MAX - 1);",
    "  type digit_len_t is array (0 to 9) of natural;",
    "  constant ANN_DIGIT : digit_tab_t := (",
]
for i, d in enumerate(DIGITS):
    cs = codes(d) + [CODE["PA0"]] * (digit_len - len(codes(d)))
    lines.append("    %d => (%s)%s  -- %s" % (i, ", ".join(str(c) for c in cs), "," if i < 9 else "", d))
lines += [
    "  );",
    "  constant ANN_DIGIT_LEN : digit_len_t := (%s);" % ", ".join(str(len(codes(d))) for d in DIGITS),
    "end package vtx_announce_pkg;",
    "",
]
pkg = os.path.join(ROOT, "rtl", "common", "votrax", "vtx_announce_pkg.vhd")
with open(pkg, "w", newline="\r\n") as f:
    f.write("\n".join(lines))
print(pkg)

board = int(sys.argv[1]) if len(sys.argv) > 1 else 3
minor = int(sys.argv[2]) if len(sys.argv) > 2 else 98
stim = os.path.join(ROOT, "sim", "votrax", "stimuli", "t6_version.txt")
with open(stim, "w", newline="\n") as f:
    f.write("# generated by tools/gen_announce.py - do not edit\n")
    f.write("clock 0x7E\nidle 5\n")
    f.write("say " + " ".join("%02X" % bus(c) for c in sentence(board, minor)) + "\n")
    f.write("idle 300\n")
print(stim, "(board %d, minor %d, %d phonemes)" % (board, minor, len(sentence(board, minor))))
