"""Generates the Votrax test scripts (*.txt) for ref_votrax, the fixed point model and
the VHDL testbench. Phonemes are given by name; the script writes BUS bytes, i.e.
what the MA-216 CPU stores to $2000: P0..P5 inverted (the board inverts, PinMAME
does data ^ 0x3f), inflection I1/I2 on D6/D7 (not inverted).

Run: python gen_stimuli.py   (writes the .txt files next to this script)
"""
import os

NAMES = ("EH3 EH2 EH1 PA0 DT A1 A2 ZH AH2 I3 I2 I1 M N B V "
         "CH SH Z AW1 NG AH1 OO1 OO L K J H G F D S "
         "A AY Y1 UH3 AH P O I U Y T R E W AE AE1 "
         "AW2 UH2 UH1 UH O2 O1 IU U1 THV TH ER EH E1 AW PA1 STOP").split()
CODE = {n: i for i, n in enumerate(NAMES)}
assert len(NAMES) == 64


def bus(name, infl=0):
    return (CODE[name] ^ 0x3F) | (infl << 6)


def say(words, infl=0):
    return "say " + " ".join("%02X" % bus(n, infl) for n in words.split())


HERE = os.path.dirname(os.path.abspath(__file__))
scripts = {
    # every phoneme once, normal clock - covers the whole phoneme ROM
    "t1_allphones": ["clock 0x7E", "idle 5",
                     say(" ".join(NAMES[:63]) + " PA0 STOP")],
    # the same vowels at the four inflection levels (pitch)
    "t2_inflection": ["clock 0x7E", "idle 5"] +
                     [say("AH AH1 AH2 PA0 E E1 PA0", i) for i in range(4)] + [say("STOP")],
    # a sentence, for listening
    "t3_sentence": ["clock 0x7E", "idle 5",
                    say("V O1 T R AE1 K S PA0 S P E1 E1 K S PA1 "
                        "F R AH1 M PA0 G AW1 T L I1 I3 B PA1 STOP")],
    # TILT as on Gottlieb: speed starts at 0xA0 and steps down by 0x0A to 0x46
    "t4_clock": ["idle 5"] +
                sum(([("clock 0x%02X" % c), say("T I1 I3 L T PA0")]
                     for c in range(0xA0, 0x45, -0x0A)), []) + [say("STOP")],
    # mute ($7000) in the middle of a word, unmute by the next phoneme write
    "t5_mute": ["clock 0x7E", "idle 5", say("AH AH AH"), "mute", "idle 30",
                say("O O O STOP")],
}

for name, lines in scripts.items():
    with open(os.path.join(HERE, name + ".txt"), "w", newline="\n") as f:
        f.write("# generated by gen_stimuli.py - do not edit\n")
        f.write("\n".join(lines) + "\n")
    print(name)
