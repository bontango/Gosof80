<#
.SYNOPSIS
  Writes rtl\hw5x_80b\mf4_table_pkg.vhd: the coefficient of rtl\hw5x_80b\mf4_filter.vhd per value
  of the register $2000 of the MA-886 generation 2.
.DESCRIPTION
  Schematic E-25549: E3 (74HC592) counts the 4 MHz from N to 255, E4 divides by 2, the MF-4-50 has
  its corner at clock / 50, so fc = 4 MHz / (256 - N) / 2 / 50 = 40 kHz / (256 - N).
  State variable filter at fs = 50 MHz / 128: f = 2 * sin(pi * fc / fs), scaled by 65536.
  Never edit the package by hand.
#>
$ErrorActionPreference = 'Stop'
$Repo = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$fs = 50000000.0 / 128.0
$sb = New-Object System.Text.StringBuilder
[void]$sb.Append("-- GENERATED by scripts\gen_mf4_table.ps1, do not edit.`r`n")
[void]$sb.Append("-- f = 2 * sin(pi * fc / fs) * 65536, fc = 40 kHz / (256 - N), fs = 50 MHz / 128`r`n")
[void]$sb.Append("package mf4_table_pkg is`r`n`ttype mf4_table_t is array (0 to 255) of integer range 0 to 65535;`r`n")
[void]$sb.Append("`tconstant MF4_TABLE : mf4_table_t := (`r`n")
for ($n = 0; $n -lt 256; $n++) {
    $fc = 40000.0 / (256 - $n)
    $f = [Math]::Round(2.0 * [Math]::Sin([Math]::PI * $fc / $fs) * 65536.0)
    if ($n % 12 -eq 0) { [void]$sb.Append("`t`t") }
    [void]$sb.Append($f)
    if ($n -ne 255) { [void]$sb.Append(',') }
    if ($n % 12 -eq 11 -or $n -eq 255) { [void]$sb.Append("`r`n") } else { [void]$sb.Append(' ') }
}
[void]$sb.Append("`t);`r`nend package mf4_table_pkg;`r`n")
[System.IO.File]::WriteAllText((Join-Path $Repo 'rtl\hw5x_80b\mf4_table_pkg.vhd'), $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
